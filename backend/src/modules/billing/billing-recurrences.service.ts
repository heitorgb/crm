import { Injectable } from '@nestjs/common';
import { BillingChargeStatus, BillingRecurrenceFrequency, Prisma } from '@prisma/client';
import { buildPage, skipOf, type PageResult } from '../../common/http/pagination.js';
import { TenantContextService } from '../../common/tenant-context/tenant-context.service.js';
import { PrismaService } from '../../infrastructure/prisma/prisma.service.js';
import { BillingInvalidDateError, BillingRecurrenceNotFoundError } from './billing.errors.js';
import { MODULE_KEYS } from '../modules/modules.constants.js';
import { ModulesService } from '../modules/modules.service.js';
import { assertBillingContact, resolveBillingParty } from './billing-party.js';
import {
  addMonthsClamped,
  formatDateOnly,
  isValidDateOnly,
  parseDateOnly,
} from './billing-time.js';
import { BILLING_MAX_RECURRENCE_CATCHUP } from './billing.constants.js';
import type {
  CreateBillingRecurrenceDto,
  ListBillingRecurrencesQueryDto,
  UpdateBillingRecurrenceDto,
} from './dto/recurrence.dto.js';

export interface BillingRecurrenceView {
  id: string;
  customerId: string | null;
  customerName: string | null;
  contactId: string | null;
  contactName: string | null;
  description: string;
  amountCents: number;
  frequency: BillingRecurrenceFrequency;
  startDate: string;
  endDate: string | null;
  nextRunDate: string;
  active: boolean;
  createdAt: Date;
  updatedAt: Date;
}

const RECURRENCE_INCLUDE = {
  customer: { select: { name: true } },
  contact: { select: { name: true } },
} satisfies Prisma.BillingRecurrenceInclude;

type PrismaRecurrence = Prisma.BillingRecurrenceGetPayload<{ include: typeof RECURRENCE_INCLUDE }>;

@Injectable()
export class BillingRecurrencesService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly tenantContext: TenantContextService,
    private readonly modules: ModulesService,
  ) {}

  async list(query: ListBillingRecurrencesQueryDto): Promise<PageResult<BillingRecurrenceView>> {
    const { tenantId } = this.tenantContext.requireContext();
    const where: Prisma.BillingRecurrenceWhereInput = { tenantId };

    if (query.active !== undefined) where.active = query.active;
    if (query.customerId) where.customerId = query.customerId;
    if (query.contactId) where.contactId = query.contactId;
    if (query.search) {
      where.description = { contains: query.search, mode: 'insensitive' };
    }

    const [total, recurrences] = await this.prisma.$transaction([
      this.prisma.billingRecurrence.count({ where }),
      this.prisma.billingRecurrence.findMany({
        where,
        orderBy: { createdAt: query.order },
        skip: skipOf(query.page, query.perPage),
        take: query.perPage,
        include: RECURRENCE_INCLUDE,
      }),
    ]);

    return buildPage(recurrences.map(toView), total, query.page, query.perPage);
  }

  async create(dto: CreateBillingRecurrenceDto): Promise<BillingRecurrenceView> {
    const { tenantId } = this.tenantContext.requireContext();
    const { recurrence } = await this.createForTenant(tenantId, dto);
    return recurrence;
  }

  /**
   * Creates a recurrence and its first charge (for the start date). Shared by
   * the recurrence endpoint and by a recurring charge creation. Subsequent
   * occurrences are generated by `generateDue` when their due date arrives.
   */
  async createForTenant(
    tenantId: string,
    dto: CreateBillingRecurrenceDto,
    client: Prisma.TransactionClient = this.prisma,
  ): Promise<{ recurrence: BillingRecurrenceView; firstChargeId: string }> {
    const party = await resolveBillingParty(client, tenantId, dto.customerId, dto.contactId);

    const startDate = requireDateOnly(dto.startDate, 'startDate');
    const endDate = dto.endDate ? requireDateOnly(dto.endDate, 'endDate') : null;
    if (endDate && endDate < startDate) {
      throw new BillingInvalidDateError('A data final não pode ser anterior à data inicial.');
    }

    const recurrence = await client.billingRecurrence.create({
      data: {
        tenantId,
        customerId: party.customerId,
        contactId: party.contactId,
        description: dto.description.trim(),
        amountCents: dto.amountCents,
        frequency: BillingRecurrenceFrequency.MONTHLY,
        startDate: parseDateOnly(startDate),
        nextRunDate: parseDateOnly(addMonthsClamped(startDate, 1)),
        endDate: endDate ? parseDateOnly(endDate) : null,
        active: true,
      },
      include: RECURRENCE_INCLUDE,
    });

    const firstCharge = await client.billingCharge.create({
      data: {
        tenantId,
        customerId: party.customerId,
        contactId: party.contactId,
        recurrenceId: recurrence.id,
        description: dto.description.trim(),
        amountCents: dto.amountCents,
        dueDate: parseDateOnly(startDate),
        status: BillingChargeStatus.PENDING,
      },
      select: { id: true },
    });

    return { recurrence: toView(recurrence), firstChargeId: firstCharge.id };
  }

  async update(id: string, dto: UpdateBillingRecurrenceDto): Promise<BillingRecurrenceView> {
    const { tenantId } = this.tenantContext.requireContext();
    const current = await this.requireRecurrence(tenantId, id);

    const data: Prisma.BillingRecurrenceUncheckedUpdateInput = {};
    if (dto.contactId !== undefined && dto.contactId !== null) {
      const contactCustomerId = await assertBillingContact(
        this.prisma,
        tenantId,
        dto.contactId,
        current.customerId,
      );
      data.contactId = dto.contactId;
      if (contactCustomerId) {
        data.customerId = contactCustomerId;
      }
    } else if (dto.contactId === null) {
      data.contactId = null;
    }

    if (dto.description !== undefined) data.description = dto.description.trim();
    if (dto.amountCents !== undefined) data.amountCents = dto.amountCents;
    if (dto.active !== undefined) data.active = dto.active;
    if (dto.endDate !== undefined) {
      data.endDate = dto.endDate ? parseDateOnly(requireDateOnly(dto.endDate, 'endDate')) : null;
    }

    const recurrence = await this.prisma.billingRecurrence.update({
      where: { id },
      data,
      include: RECURRENCE_INCLUDE,
    });
    return toView(recurrence);
  }

  /** Stops future generation without removing already generated charges. */
  async deactivate(id: string): Promise<BillingRecurrenceView> {
    const { tenantId } = this.tenantContext.requireContext();
    await this.requireRecurrence(tenantId, id);

    const recurrence = await this.prisma.billingRecurrence.update({
      where: { id },
      data: { active: false },
      include: RECURRENCE_INCLUDE,
    });
    return toView(recurrence);
  }

  /**
   * System routine executed by the billing scan. Generates every charge whose due
   * date has already been reached, without going ahead of `today`, so future
   * charges are never created indefinitely. The unique (recurrenceId, dueDate)
   * constraint makes repeated runs idempotent.
   */
  async generateDue(today: string): Promise<number> {
    const due = await this.prisma.billingRecurrence.findMany({
      where: { active: true, nextRunDate: { lte: parseDateOnly(today) } },
    });

    let created = 0;
    const chargesEnabled = new Map<string, boolean>();
    for (const recurrence of due) {
      let enabled = chargesEnabled.get(recurrence.tenantId);
      if (enabled === undefined) {
        enabled = await this.modules.isEnabled(recurrence.tenantId, MODULE_KEYS.BILLING_CHARGES);
        chargesEnabled.set(recurrence.tenantId, enabled);
      }
      if (!enabled) {
        continue;
      }

      const endDate = recurrence.endDate ? formatDateOnly(recurrence.endDate) : null;
      let cursor = formatDateOnly(recurrence.nextRunDate);
      let iterations = 0;

      while (cursor <= today && iterations < BILLING_MAX_RECURRENCE_CATCHUP) {
        if (endDate && cursor > endDate) {
          break;
        }

        try {
          await this.prisma.billingCharge.create({
            data: {
              tenantId: recurrence.tenantId,
              customerId: recurrence.customerId,
              contactId: recurrence.contactId,
              recurrenceId: recurrence.id,
              description: recurrence.description,
              amountCents: recurrence.amountCents,
              dueDate: parseDateOnly(cursor),
              status: BillingChargeStatus.PENDING,
            },
          });
          created += 1;
        } catch (error) {
          if (!(error instanceof Prisma.PrismaClientKnownRequestError && error.code === 'P2002')) {
            throw error;
          }
        }

        cursor = addMonthsClamped(cursor, 1);
        iterations += 1;
      }

      const exhausted = endDate !== null && cursor > endDate;
      await this.prisma.billingRecurrence.update({
        where: { id: recurrence.id },
        data: {
          nextRunDate: parseDateOnly(cursor),
          ...(exhausted ? { active: false } : {}),
        },
      });
    }

    return created;
  }

  private async requireRecurrence(tenantId: string, id: string) {
    const recurrence = await this.prisma.billingRecurrence.findFirst({ where: { id, tenantId } });
    if (!recurrence) {
      throw new BillingRecurrenceNotFoundError();
    }
    return recurrence;
  }
}

function toView(recurrence: PrismaRecurrence): BillingRecurrenceView {
  return {
    id: recurrence.id,
    customerId: recurrence.customerId,
    customerName: recurrence.customer?.name ?? null,
    contactId: recurrence.contactId,
    contactName: recurrence.contact?.name ?? null,
    description: recurrence.description,
    amountCents: recurrence.amountCents,
    frequency: recurrence.frequency,
    startDate: formatDateOnly(recurrence.startDate),
    endDate: recurrence.endDate ? formatDateOnly(recurrence.endDate) : null,
    nextRunDate: formatDateOnly(recurrence.nextRunDate),
    active: recurrence.active,
    createdAt: recurrence.createdAt,
    updatedAt: recurrence.updatedAt,
  };
}

function requireDateOnly(value: string, field: string): string {
  if (!isValidDateOnly(value)) {
    throw new BillingInvalidDateError(`Data inválida em "${field}". Use o formato YYYY-MM-DD.`);
  }
  return value;
}
